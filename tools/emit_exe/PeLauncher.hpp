inline bool writeHostLauncherExe(const std::string& exePath, const std::string& command) {
    std::vector<unsigned char> pe(kPeTemplate, kPeTemplate + sizeof(kPeTemplate));
    std::string cmd = command;
    if (cmd.size() > kCmdMax) cmd.resize(kCmdMax);
    // Zero the command slot then copy
    std::memset(pe.data() + kCmdFileOff, 0, kCmdMax + 1);
    std::memcpy(pe.data() + kCmdFileOff, cmd.data(), cmd.size());
    std::ofstream out(exePath, std::ios::binary);
    if (!out) return false;
    out.write(reinterpret_cast<const char*>(pe.data()), static_cast<std::streamsize>(pe.size()));
    return (bool)out;
}
